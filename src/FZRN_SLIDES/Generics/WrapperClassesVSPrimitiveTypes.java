package FZRN_SLIDES.Generics;

public class WrapperClassesVSPrimitiveTypes {
    public static void main(String[] args) {
        // Primitive
        int num = 5;

        // Wrapper
        Integer obj = 5;

        System.out.println("Primitive: " + num);
        System.out.println("Wrapper: " + obj);
    }
}
